// 配合 styles/main.css 的 .tip-term，以及 src/main.js 全局
// .tip[data-tip] / .tip-term[data-tip] mouseover 监听。
//
// 注意 data-tip 内容必须避免裸单引号，attachTermTips() 会做 ' → &#39; 转义。

// 把已经高亮过的 <b class="term-xxx">关键词</b> 转换为带 tooltip 的
// .tip-term[data-tip='...'] 包裹，鼠标悬停时自动弹出 TERM_DICT 中的解释。
export function attachTermTips(html) {
  if (!html) return '';
  return html.replace(/<b\s+class="term-(\w+)"\s*>([^<]+)<\/b>/g, (match, cls, keyword) => {
    const trimmed = keyword.trim();
    const dictKey = Object.keys(TERM_DICT).find(k => trimmed.startsWith(k) || k.startsWith(trimmed));
    let tip = dictKey ? TERM_DICT[dictKey] : null;
    if (!tip) {
      // fallback：尝试从 term-xxx 的 cls 推测（资源名/类型名）
      tip = `<b style="color:var(--accent)">${trimmed}</b><br>角色专属机制，详情见角色技能说明。`;
    }
    // data-tip 内单引号转义，避免 HTML 属性边界问题
    const safeTip = tip.replace(/'/g, '&#39;');
    return `<span class="tip-term" data-tip='${safeTip}'>${trimmed}</span>`;
  });
}

